"""Cinema P26 — second-generation H.264 recompression of exclusively fictional P25 clips.

Independent nine-pair CRF18/25/32 matrix with 480-frame decoded audits.
The input is generated by actual P19/P23/P25 engines. Audio must be copied
unchanged at the decoded PCM level. This is NOT a platform X emulator, iPhone
test, neural video model, automatic export policy, or human realism test.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import math
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import numpy as np

ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/"p25"/"src"))
from p25_crf_matrix import (
    PROFILES,NFRAMES,verify_source,peaks_for,run_checked,
    decoder,decode_one,probe_video,percentile95,
    draw_p19,blend_p23,mouth_roi,load_controls,
)

VERSION="retouche-cinema-p26-second-generation-h264-v1"
FIXTURE_PREFIX="P25_CRF"
SECOND_PREFIX="P26_pass2_"
PREVIEW_PAIR=(25,32)


def validate_pair(first,second):
    if type(first) is not int or type(second) is not int or first not in PROFILES or second not in PROFILES:
        raise ValueError("Only approved P25 18/25/32 synthetic CRF pairs accepted")
    return first,second


def expected_first_path(source_dir,crf):
    validate_pair(crf,crf)
    path=Path(source_dir)/f"P25_CRF{crf}_synthetic_H264_AAC.mp4"
    if not path.is_file() or path.stat().st_size<=10_000:
        raise ValueError("Missing original P25 synthetic video fixture")
    return path


def encode_again(source,out,first,second):
    """Re-encode video only; copy AAC elementary packets without re-encoding."""
    validate_pair(first,second)
    if Path(source).name!=f"P25_CRF{first}_synthetic_H264_AAC.mp4":
        raise ValueError("Only named original P25 synthetic clip may be recompressed")
    probe_video(source,expect_audio=True)
    args=["ffmpeg","-nostdin","-y","-hide_banner","-loglevel","error",
          "-i",str(source),"-map","0:v:0","-map","0:a:0",
          "-c:v","libx264","-preset","ultrafast","-crf",str(second),
          "-pix_fmt","yuv420p","-g","60","-keyint_min","60",
          "-sc_threshold","0","-threads","2",
          "-c:a","copy","-t","8","-movflags","+faststart",str(out)]
    run_checked(args)
    return probe_video(out,expect_audio=True)


def decoded_audio_fingerprint(path):
    """PCM digest verifies same decoded synthetic audio after stream copy."""
    cmd=["ffmpeg","-nostdin","-v","error","-i",str(path),
         "-map","0:a:0","-f","s16le","-ac","1","-ar","24000","pipe:1"]
    pcm=run_checked(cmd)
    if not 300000<=len(pcm)<=420000:
        raise ValueError("AAC synthetic audio missing or truncated")
    return {"sha256":hashlib.sha256(pcm).hexdigest(),"pcm_bytes":len(pcm)}


def check_audio_preserved(source,transcoded):
    src=decoded_audio_fingerprint(source)
    dst=decoded_audio_fingerprint(transcoded)
    if src!=dst:
        raise ValueError("Synthetic AAC audio changed on recompression")
    return True


def mouth_mae(a,b,region):
    aa=a[region].astype(np.int16)
    bb=b[region].astype(np.int16)
    return float(np.mean(np.abs(aa-bb)))


def validate_second_generation_report(row):
    if not isinstance(row,dict) or row.get("frames_compared")!=480 or row.get("transitions_compared")!=479:
        raise ValueError("Incomplete second-generation comparison")
    if row.get("audio_pcm_digest_equal") is not True:
        raise ValueError("Synthetic audio could not be proven unchanged")
    if len(row.get("gesture_peak_comparisons",{}))!=4:
        raise ValueError("Missing gesture peaks")
    if not math.isfinite(row.get("p95_additional_rgb_mae_vs_source",float("nan"))):
        raise ValueError("Invalid pixel audit metrics")
    return True


def assess_second_generation(data,first,second,first_movie,second_movie):
    validate_pair(first,second)
    first_meta=probe_video(first_movie,expect_audio=True)
    second_meta=probe_video(second_movie,expect_audio=True)
    audio_same=check_audio_preserved(first_movie,second_movie)
    a=decoder(first_movie)
    b=decoder(second_movie)
    loss_a=[]
    loss_b=[]
    motion_delta=[]
    peak={}
    positions=peaks_for(data)
    peak_by_index={i:label for label,i in positions.items()}
    last_a=None
    last_b=None
    frames_compared=0
    try:
        for i,pose in enumerate(data["frames"]):
            base=draw_p19(pose,i,NFRAMES)
            original=blend_p23(base,pose)
            frame_a=decode_one(a)
            frame_b=decode_one(b)
            x0,y0,x1,y1=mouth_roi(original,pose)
            roi=np.s_[y0:y1,x0:x1]
            err_a=mouth_mae(original,frame_a,roi)
            err_b=mouth_mae(original,frame_b,roi)
            loss_a.append(err_a)
            loss_b.append(err_b)
            if last_a is not None:
                d_a=mouth_mae(frame_a,last_a,roi)
                d_b=mouth_mae(frame_b,last_b,roi)
                # Difference in consecutive-frame pixel change after pass two.
                # This is a codec perturbation, NOT measured playback stutter.
                motion_delta.append(abs(d_b-d_a))
            if i in peak_by_index:
                peak[peak_by_index[i]]={
                    "frame":i,
                    "mae_pass1_vs_original":round(err_a,6),
                    "mae_pass2_vs_original":round(err_b,6),
                    "pass2_minus_pass1_mae":round(err_b-err_a,6),
                    "pass1_vs_pass2_changed_pixels_threshold8":
                      int(np.count_nonzero(np.any(
                          np.abs(frame_a[roi].astype(np.int16)-frame_b[roi].astype(np.int16))>=8,axis=2))),
                }
            last_a=frame_a
            last_b=frame_b
            frames_compared+=1
        if a.stdout.read(1) or b.stdout.read(1):
            raise ValueError("Unexpected decoded frames after 480")
    finally:
        for proc in (a,b):
            if proc.stdout:proc.stdout.close()
            if proc.poll() is None:proc.wait(timeout=30)
            if proc.stderr:proc.stderr.close()
    if a.returncode or b.returncode:
        raise RuntimeError("Second-generation FFmpeg decoding failed")
    row={
        "pass1_crf":first,"pass2_crf":second,
        "first_mp4_bytes":Path(first_movie).stat().st_size,
        "second_mp4_bytes":Path(second_movie).stat().st_size,
        "relative_size_change_pct":round(100*(Path(second_movie).stat().st_size/
                                  Path(first_movie).stat().st_size-1),3),
        "first_metadata":first_meta,"second_metadata":second_meta,
        "frames_compared":frames_compared,
        "transitions_compared":len(motion_delta),
        "p95_first_generation_rgb_mae":percentile95(loss_a),
        "p95_second_generation_rgb_mae":percentile95(loss_b),
        "p95_additional_rgb_mae_vs_source":percentile95([max(0,z-y) for y,z in zip(loss_a,loss_b)]),
        "mean_pass1_rgb_mae":round(float(np.mean(loss_a)),6),
        "mean_pass2_rgb_mae":round(float(np.mean(loss_b)),6),
        "p95_adjacent_frame_change_perturbation":percentile95(motion_delta),
        "gesture_peak_comparisons":peak,
        "audio_pcm_digest_equal":audio_same,
        "gesture_realism_verified":False,
        "codec_perturbation_is_not_playback_stutter":True,
    }
    validate_second_generation_report(row)
    return row


def audit_matrix(data,source_dir,out_dir):
    verify_source(data)
    out_dir=Path(out_dir)
    out_dir.mkdir(parents=True,exist_ok=True)
    files={crf:expected_first_path(source_dir,crf) for crf in PROFILES}
    rows=[]
    with tempfile.TemporaryDirectory(prefix="cinema-p26-reencode-") as tmp:
        temp=Path(tmp)
        for first in PROFILES:
            for second in PROFILES:
                output=(out_dir if (first,second)==PREVIEW_PAIR else temp)/(
                    f"{SECOND_PREFIX}{first}_to_{second}_synthetic_H264_AAC.mp4")
                encode_again(files[first],output,first,second)
                rows.append(assess_second_generation(data,first,second,files[first],output))
    if len(rows)!=9 or {(r["pass1_crf"],r["pass2_crf"]) for r in rows}!=set(
        (a,b) for a in PROFILES for b in PROFILES):
        raise ValueError("Second-generation nine-case matrix incomplete")
    report={
        "schema":VERSION,"status":"synthetic_second_generation_measured",
        "source":"P19_P21_P22_P23_P25_fictional_control_rendering_only",
        "profiles_first_pass":list(PROFILES),"profiles_second_pass":list(PROFILES),
        "video_stream_comparisons":9,
        "frames_per_comparison":NFRAMES,
        "transitions_per_comparison":NFRAMES-1,
        "summary":rows,
        "reported_perceptual_stutter":False,
        "no_universal_crf_choice":True,
        "source_media_private":False,
        "actual_people_or_real_annotations_used":False,
        "training_performed":False,
        "physical_iphone_safari_tested":False,
        "second_generation_audio_preserved":all(row["audio_pcm_digest_equal"] for row in rows),
        "no_network_deployment":True,
        "no_automatic_app_integration":True,
    }
    (out_dir/"p26_second_generation_synthetic_report.json").write_text(json.dumps(report,indent=2),encoding="utf-8")
    return report


def main():
    ap=argparse.ArgumentParser()
    ap.add_argument("--data",type=Path,required=True)
    ap.add_argument("--source-dir",type=Path,required=True)
    ap.add_argument("--out",type=Path,required=True)
    args=ap.parse_args()
    report=audit_matrix(load_controls(args.data),args.source_dir,args.out)
    print(json.dumps({"status":report["status"],"cases":report["video_stream_comparisons"],
         "audio_preserved":report["second_generation_audio_preserved"],
         "rows":[{"first":r["pass1_crf"],"second":r["pass2_crf"],
             "size_bytes":r["second_mp4_bytes"],"p95_mae_first":r["p95_first_generation_rgb_mae"],
             "p95_mae_second":r["p95_second_generation_rgb_mae"],
             "p95_additional_error":r["p95_additional_rgb_mae_vs_source"],
             "p95_motion_perturbation":r["p95_adjacent_frame_change_perturbation"]}
             for r in report["summary"]]},indent=2))


if __name__=="__main__":
    main()
