"""Experimental no-training consistency projection for 2x video super-resolution.

Given a predicted HR image and its known synthetic LR input, apply exactly ONE
luminance-offset back-projection step toward area-downsample consistency.
Not a hallucination/face check or a guarantee for real-world camera degradation.
Never automatically deploy this research correction.
"""
from __future__ import annotations
import cv2
import numpy as np

def _check(sr:np.ndarray, lr:np.ndarray):
    for a in (sr,lr):
        if not isinstance(a,np.ndarray) or a.ndim!=3 or a.shape[2]!=3 or a.dtype!=np.uint8:
            raise TypeError('BGR uint8 images required')
    h,w=lr.shape[:2]
    if sr.shape!=(2*h,2*w,3):raise ValueError('Source must be exactly x2')
    if h<16 or w<16 or h*w>1920*1080:raise ValueError('Unsupported source dimensions')

def input_luma_consistency(sr:np.ndarray,lr:np.ndarray)->float:
    """Mean absolute 8-bit luma error after simulated area downsampling."""
    _check(sr,lr)
    ysr=cv2.cvtColor(sr,cv2.COLOR_BGR2GRAY)
    ylr=cv2.cvtColor(lr,cv2.COLOR_BGR2GRAY)
    area=cv2.resize(ysr,(lr.shape[1],lr.shape[0]),interpolation=cv2.INTER_AREA)
    return float(np.mean(np.abs(area.astype(np.float32)-ylr.astype(np.float32))))

def project_once(sr:np.ndarray,lr:np.ndarray,*,known_area_downsample:bool=False)->tuple[np.ndarray,dict]:
    """One physics-based projection step, no tuning on evaluation data.

    Operates by adding the SAME grayscale offset to B,G,R. All outputs and
    inputs remain BGR8 and the output is detached from source arrays.
    This technique is valid only when the LR was generated by the known area
    downsampling operator. JPEG destroys this assumption, so testing it under
    JPEG is exploratory and NOT authorization for a product preset.
    """
    if type(known_area_downsample) is not bool or known_area_downsample is not True:
        raise PermissionError('Projection requires a verified area-downsample forward operator')
    _check(sr,lr)
    h,w=lr.shape[:2]
    orig_y=cv2.cvtColor(sr,cv2.COLOR_BGR2GRAY)
    low_y=cv2.cvtColor(lr,cv2.COLOR_BGR2GRAY)
    down=cv2.resize(orig_y,(w,h),interpolation=cv2.INTER_AREA)
    err=low_y.astype(np.float32)-down.astype(np.float32)
    correction=cv2.resize(err,(2*w,2*h),interpolation=cv2.INTER_LINEAR)
    out=np.clip(np.rint(sr.astype(np.float32)+correction[:,:,None]),0,255).astype(np.uint8)
    before=float(np.abs(err).mean())
    after=input_luma_consistency(out,lr)
    return out,{
      'before_luma_lr_mae_255':round(before,5),
      'after_luma_lr_mae_255':round(after,5),
      'mean_abs_pixel_adjustment_255':round(float(np.abs(out.astype(np.float32)-sr.astype(np.float32)).mean()),5),
      'learned_parameters_updated':False,
      'operator_known_simulated_area_downsample':True,
      'valid_for_unknown_real_camera_pipeline':False,
      'verified_face_fidelity':False,
      'automatic_deployment':False,
    }
