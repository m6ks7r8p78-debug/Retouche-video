'use strict';
const assert=require('node:assert/strict');
const b=require('../smallmotion-director-local.js');
const m=require('../smallmotion-local.js');
let checks=0;
function eq(a,bv){assert.deepEqual(a,bv);checks++}
const file={name:'local.mov',type:'video/quicktime',size:1024};
eq(b.eligibility(file),null);
eq(b.eligibility({...file,type:'',name:'video_local.MOV'}),null);
eq(b.eligibility({...file,size:0}),'file_out_of_budget');
eq(b.eligibility({...file,size:121*1024*1024}),'file_out_of_budget');
eq(b.eligibility({...file,type:'image/jpeg'}),'not_video');
eq(b.eligibility(file,{hidden:true}),'page_hidden');
eq(b.eligibility(file,{framesAPI:false}),'frames_api_unavailable');
eq(b.measureSize(1920,1080),[160,90]);
eq(b.measureSize(1080,1920),[67,120]);
eq(b.measureSize(6000,600),null);
eq(b.measureSize(NaN,100),null);
const sample={times:[0.0,0.14],width:160,height:120};
const raw={status:'local_motion_candidate',candidates:[{box:[40,20,20,30],support:5}]};
const evidence=b.observation(raw,sample,8.3);
eq(evidence.status,'local_motion_candidate');eq(evidence.action,'no_automatic_change');eq(evidence.candidates.length,1);eq(evidence.confidence,'not_calibrated');
assert.ok(!('file' in evidence));checks++;
assert.ok(!('model' in evidence));checks++;
assert.ok(Object.isFrozen(evidence));checks++;
eq(b.observation(raw,{...sample,times:[0,0]},8).status,'abstain_invalid_evidence');
eq(b.observation(raw,{...sample,times:[0,0.04]},8).status,'abstain_invalid_evidence');
eq(b.observation({...raw,candidates:[{box:[154,20,20,30],support:5}]},sample,8).status,'abstain_invalid_evidence');
eq(b.observation({status:'contact_confirmed',candidates:[]},sample,8).status,'abstain_invalid_evidence');
eq(b.observation({status:'no_supported_local_motion',candidates:[]},sample,8).candidates.length,0);
const blank=new Uint8ClampedArray(160*120*4);blank.fill(100);
const r=m.analyze({width:160,height:120,data:blank},{width:160,height:120,data:blank});
eq(r.status,'abstain_texture');
eq(b.observation(r,sample,1).candidates.length,0);
assert.equal(typeof b.sampleLocalVideo,'function');checks++;
assert.equal(typeof b.mount,'function');checks++;
console.log(`Local Director bridge: ${checks} assertions passed`);