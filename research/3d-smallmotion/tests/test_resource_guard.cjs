'use strict';
const assert=require('node:assert/strict');
const g=require('../smallmotion-resource-guard.js');
const bridge=require('../smallmotion-director-local.js');
let n=0;function check(name,predicate){assert.ok(predicate,name);n++}
const input={captureMs:750,processorMs:32.22,width:160,height:120};
let r=g.assess(input);
check('normal state',r.state==='within_budget');
check('native decoder memory unavailable',r.nativeVideoDecoderBytes===null);
check('no fake temperature',r.deviceTemperatureC===null);
check('no fake battery',r.batteryConsumption===null);
check('bounded owned memory estimate',r.estimatedCpuOwnedBytes===160*120*14);
check('frozen',Object.isFrozen(r));
check('default full',r.nextProfile==='full');
r=g.assess({...input,processorMs:81});
check('slower phase recorded',r.state==='slow');
check('next run reduced',r.nextProfile==='reduced');
r=g.assess({...input,processorMs:501});
check('processor budget exceed',r.state==='abstain');
check('next reduced after exceed',r.nextProfile==='reduced');
check('capture budget exceed',g.assess({...input,captureMs:6001}).state==='abstain');
check('hidden page abstains',g.assess({...input,visibility:'hidden'}).state==='abstain');
check('bad dimension abstains',g.assess({...input,width:161}).state==='abstain');
check('invalid data abstains',g.assess({...input,processorMs:NaN}).state==='abstain');
check('reduced accepted',g.assess({...input,width:128,height:96,profile:'reduced'}).nextProfile==='reduced');
check('portrait aspect',JSON.stringify(bridge.measureSize(1080,1920,[128,96]))==='null');
check('full portrait accepted',JSON.stringify(bridge.measureSize(1080,1920))==='[67,120]');
let sample={times:[0.033,0.1667],width:160,height:120};
let src={status:'local_motion_candidate',candidates:[{box:[30,30,18,18],support:8}]};
let m=bridge.observation(src,sample,501,g.assess({...input,processorMs:501}));
check('expensive evidence never accepted',m.status==='abstain_resource_budget');
check('no candidates when too slow',m.candidates.length===0);
check('no automatic change',m.action==='no_automatic_change');
check('timings preserved',m.resourceEvaluation.captureMs===750);
check('no media bytes',!('data' in m) && !('filename' in m));
let fast=bridge.observation(src,sample,20,g.assess(input));
check('moderate evidence preserved',fast.status==='local_motion_candidate'&&fast.candidates.length===1);
check('non calibrated',fast.confidence==='not_calibrated');
console.log('Resource guard:',n,'checks passed');